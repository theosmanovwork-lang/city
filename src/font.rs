#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fonts_load_and_ramps_are_monotonic() {
        for id in FontId::ALL {
            let f = Font::load(id);
            let mut prev = -1.0;
            for (k, &g) in f.ramp_glyphs.iter().enumerate() {
                let c = f.coverage(g);
                let ch = glyph_char(g);
                println!("{} рампа[{k}] {ch:?} покрытие {:.2}", f.name, c);
                assert!(c >= prev, "{}: рампа не монотонна на {ch:?}", f.name);
                prev = c;
            }
        }
    }

    #[test]
    fn glyph_index_roundtrip() {
        for g in 0..GLYPH_COUNT as u16 {
            assert_eq!(glyph_index(glyph_char(g)), g);
        }
        assert_eq!(glyph_index('Ж'), glyph_index('?'));
    }
}
