//! Собственные пиксельные шрифты: 3×5, 4×6 и 5×8 (размер глифа без зазора).
//!
//! Глифы нарисованы попиксельно прямо в коде: каждая строка — ряд пикселей
//! сверху вниз, `#` — пиксель горит, `.` — пусто. Блочные символы и дизеринг
//! (`█ ▄ ▀ ░ ▒ ▓`) генерируются процедурно, чтобы на любом размере быть точными.
//!
//! Индекс глифа (`u16`) общий для всех шрифтов: 0..=94 — ASCII 32..=126,
//! дальше — блоки. Поэтому сетка не зависит от выбранного шрифта.
//! Новые символы (например, кириллица) добавляются в конец `EXTRA`.

/// Дополнительные символы после ASCII (порядок = индекс глифа).
pub const EXTRA: [char; 6] = ['█', '▄', '▀', '░', '▒', '▓'];
/// Число глифов в каждом шрифте.
pub const GLYPH_COUNT: usize = 95 + EXTRA.len();
/// Сколько глифов в ряду атласа.
pub const ATLAS_COLS: u32 = 16;

/// Индекс глифа для символа; неизвестные символы → `?`.
pub fn glyph_index(c: char) -> u16 {
    let code = c as u32;
    if (32..=126).contains(&code) {
        return (code - 32) as u16;
    }
    match EXTRA.iter().position(|&e| e == c) {
        Some(k) => (95 + k) as u16,
        None => glyph_index('?'),
    }
}

/// Символ по индексу глифа (для отладки и тестов).
pub fn glyph_char(g: u16) -> char {
    let g = g as usize;
    if g < 95 { char::from(32 + g as u8) } else { EXTRA.get(g - 95).copied().unwrap_or('?') }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FontId {
    Tiny,   // 3×5
    Small,  // 4×6
    Normal, // 5×8
}

impl FontId {
    pub const ALL: [FontId; 3] = [FontId::Tiny, FontId::Small, FontId::Normal];
}

/// Растеризованный шрифт: маски глифов + рампа плотности.
pub struct Font {
    pub name: &'static str,
    pub w: u32,
    pub h: u32,
    /// `GLYPH_COUNT * w * h` байт, 0 или 1, построчно внутри глифа.
    pub pixels: Vec<u8>,
    /// Рампа плотности: от пустого к самому «тяжёлому», только хорошо различимые символы.
    pub ramp: &'static str,
    /// Та же рампа в индексах глифов.
    pub ramp_glyphs: Vec<u16>,
}

impl Font {
    pub fn load(id: FontId) -> Font {
        let (name, w, h, table, ramp) = match id {
            FontId::Tiny => ("3x5", 3, 5, FONT_3X5, RAMP_3X5),
            FontId::Small => ("4x6", 4, 6, FONT_4X6, RAMP_4X6),
            FontId::Normal => ("5x8", 5, 8, FONT_5X8, RAMP_5X8),
        };
        let mut font = Font {
            name,
            w,
            h,
            pixels: vec![0; GLYPH_COUNT * (w * h) as usize],
            ramp,
            ramp_glyphs: ramp.chars().map(glyph_index).collect(),
        };
        let mut defined = [false; 95];
        for &(c, rows) in table {
            let g = glyph_index(c) as usize;
            assert!(g < 95 && !defined[g], "шрифт {name}: символ {c:?} повторяется");
            defined[g] = true;
            let rows: Vec<&str> = rows.split_whitespace().collect();
            assert_eq!(rows.len(), h as usize, "шрифт {name}: символ {c:?} — не {h} строк");
            for (y, row) in rows.iter().enumerate() {
                assert_eq!(row.len(), w as usize, "шрифт {name}: символ {c:?} — строка не {w} пикс.");
                for (x, p) in row.bytes().enumerate() {
                    font.set(g, x as u32, y as u32, p == b'#');
                }
            }
        }
        if let Some(missing) = defined.iter().position(|d| !d) {
            panic!("шрифт {name}: нет символа {:?}", glyph_char(missing as u16));
        }
        font.build_blocks();
        font
    }

    fn set(&mut self, g: usize, x: u32, y: u32, on: bool) {
        let i = g * (self.w * self.h) as usize + (y * self.w + x) as usize;
        self.pixels[i] = on as u8;
    }

    pub fn pixel(&self, g: u16, x: u32, y: u32) -> bool {
        self.pixels[g as usize * (self.w * self.h) as usize + (y * self.w + x) as usize] != 0
    }

    /// Доля горящих пикселей глифа (0..1) — «плотность».
    #[cfg(test)]
    pub fn coverage(&self, g: u16) -> f32 {
        let n = (self.w * self.h) as usize;
        let s = &self.pixels[g as usize * n..(g as usize + 1) * n];
        s.iter().map(|&p| p as u32).sum::<u32>() as f32 / n as f32
    }

    /// Блоки и дизеринг: █ ▄ ▀ ░ ▒ ▓.
    fn build_blocks(&mut self) {
        let half = self.h / 2;
        for (k, &c) in EXTRA.iter().enumerate() {
            let g = 95 + k;
            for y in 0..self.h {
                for x in 0..self.w {
                    let on = match c {
                        '█' => true,
                        '▄' => y >= half,
                        '▀' => y < half,
                        '░' => x % 2 == 0 && y % 2 == 0,    // 1/4
                        '▒' => (x + y) % 2 == 0,            // 1/2 шахматка
                        '▓' => !(x % 2 == 1 && y % 2 == 1), // 3/4
                        _ => false,
                    };
                    self.set(g, x, y, on);
                }
            }
        }
    }
}

/// Атлас всех шрифтов: R8, шрифты лежат друг под другом,
/// внутри шрифта — `ATLAS_COLS` глифов в ряду, глифы без масштаба и без зазора.
pub struct Atlas {
    pub width: u32,
    pub height: u32,
    pub data: Vec<u8>,
    /// Y-смещение каждого шрифта в атласе (в порядке `FontId::ALL`).
    pub origin_y: [u32; 3],
}

impl Atlas {
    pub fn build(fonts: &[Font; 3]) -> Atlas {
        let rows = (GLYPH_COUNT as u32).div_ceil(ATLAS_COLS);
        let width = fonts.iter().map(|f| f.w * ATLAS_COLS).max().unwrap_or(1);
        let mut origin_y = [0; 3];
        let mut height = 0;
        for (k, f) in fonts.iter().enumerate() {
            origin_y[k] = height;
            height += rows * f.h;
        }
        let mut data = vec![0u8; (width * height) as usize];
        for (k, f) in fonts.iter().enumerate() {
            for g in 0..GLYPH_COUNT as u16 {
                let sx = (g as u32 % ATLAS_COLS) * f.w;
                let sy = origin_y[k] + (g as u32 / ATLAS_COLS) * f.h;
                for y in 0..f.h {
                    for x in 0..f.w {
                        if f.pixel(g, x, y) {
                            data[((sy + y) * width + sx + x) as usize] = 255;
                        }
                    }
                }
            }
        }
        Atlas { width, height, data, origin_y }
    }
}

